def fix_case(template: str) -> str:
    """«в {city}» → «в городе {city}»: предложный падеж канцелярским аппозитивом."""
    for prep in ("В", "в", "около", "из"):
        template = template.replace(f"{prep} {{city}}", f"{prep} городе {{city}}" if prep in "Вв" else f"{prep} города {{city}}")
    template = template.replace("больнице {city}", "больнице города {city}")
    return template


def build_appeal(rng: random.Random, n_id: int) -> tuple[str, str, dict, str]:
    """Возвращает (тема, регион, данные обращения, markdown-секция)."""
    theme = rng.choice(list(THEME_CORES))
    region = rng.choice(list(REGIONS))
    city = rng.choice(REGIONS[region])
    street = rng.choice(STREETS)
    core = fix_case(rng.choice(THEME_CORES[theme])).format(
        city=city, street=street, n=rng.randint(1, 99), duration=rng.choice(DURATIONS)
    )
    opening = rng.choice(OPENINGS)
    closing = rng.choice(CLOSINGS).format(
        agency=rng.choice(AGENCIES), city=city, street=street
    )
    date = f"{rng.randint(1, 28)} {rng.choice(MONTHS)} {rng.randint(2025, 2026)}"
    status = rng.choices(STATUSES, weights=[50, 30, 20])[0]

    meta = {"theme": theme, "region": region, "city": city, "status": status}
    section = (
        f"### APP-{n_id:04d} — {theme} · {region}\n\n"
        f"**Регион:** {region}  \n**Город:** {city}  \n"
        f"**Дата:** {date}  \n**Статус:** {status}\n\n"
        f"{opening} {core} {closing}\n"
    )
    return theme, region, meta, section


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("count", nargs="?", type=int, default=360)
    parser.add_argument("--seed", type=int, default=42)
    parser.add_argument("--out", default="data/project_corpus.md")
    args = parser.parse_args()

    rng = random.Random(args.seed)
    lines = [
        "# Проектный корпус: обращения граждан",
        "",
        "Синтетический корпус, собранный шаблонным генератором "
        "(scripts/make_corpus.py) для проверки RAG-пайплайна. "
        "Обращения структурированы по темам, справочный раздел содержит "
        "процедурную информацию.",
        "",
        REFERENCE,
        "## Обращения граждан",
        "",
    ]

    themes_counter: Counter = Counter()
    regions_counter: Counter = Counter()
    for i in range(1, args.count + 1):
        theme, region, _meta, section = build_appeal(rng, i)
        themes_counter[theme] += 1
        regions_counter[region] += 1
        lines.append(section)

    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines), encoding="utf-8")

    print(f"Записано: {out}")
    print(f"Обращений: {args.count} (+ справочник), seed={args.seed}")
    print("По темам:", dict(themes_counter.most_common()))
    print("По регионам:", dict(regions_counter.most_common()))
    print(f"Размер: {out.stat().st_size / 1024:.0f} КБ")


if __name__ == "__main__":
    sys.exit(main())
